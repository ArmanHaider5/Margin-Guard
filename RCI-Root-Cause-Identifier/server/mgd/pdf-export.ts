/**
 * Generate a premium executive operational diagnostic PDF from a MGDReport.
 * Returns a Buffer of the PDF binary.
 * Never throws — any page failure is caught and a fallback error page is written.
 */
export async function generateMGDPdfReport(report: MGDReport): Promise<Buffer> {
  console.log("[MGD][PDF] generateMGDPdfReport — start");
  const startedAt = Date.now();

  return new Promise((resolve, reject) => {
    try {
      const doc = new PDFDocument({
        size:    "A4",
        margins: { top: MARGIN, bottom: MARGIN + 10, left: MARGIN, right: MARGIN },
        info: {
          Title:   `MGD Operational Diagnostic Report — ${safeText(report?.metadata?.clientName, "Client")}`,
          Author:  "MGD Operational Intelligence · Scope Optix Sdn. Bhd.",
          Subject: "Operational Diagnostic Report",
          Keywords:"MGD, operational intelligence, root cause, benchmarks, recommendations",
          Creator: "MGD-V1",
        },
        autoFirstPage: false,
      });

      const chunks: Buffer[] = [];
      doc.on("data",  chunk => chunks.push(chunk));
      doc.on("error", err   => { console.error("[MGD][PDF] PDFKit stream error:", err); reject(err); });
      doc.on("end",   ()    => {
        const buf = Buffer.concat(chunks);
        console.log(`[MGD][PDF] Complete — ${buf.length} bytes, ${Date.now() - startedAt}ms`);
        resolve(buf);
      });

      const TOTAL_PAGES = 7;
      const pages: Array<{ name: string; fn: (doc: PDFKit.PDFDocument, report: MGDReport) => void }> = [
        { name: "Cover",            fn: renderCover          },
        { name: "Summary",          fn: renderSummary        },
        { name: "Benchmarks",       fn: renderBenchmarks     },
        { name: "Findings",         fn: renderFindings       },
        { name: "Root Causes",      fn: renderRootCauses     },
        { name: "Recommendations",  fn: renderRecommendations },
        { name: "Narrative",        fn: renderNarrative      },
      ];

      pages.forEach((page, i) => {
        const pageNum = i + 1;
        doc.addPage();
        console.log(`[MGD][PDF] Rendering page ${pageNum}/${TOTAL_PAGES} — ${page.name}`);
        try {
          page.fn(doc, report);
        } catch (err) {
          console.error(`[MGD][PDF] Page ${pageNum} (${page.name}) render error:`, err);
          doc.font(F.regular).fontSize(9).fillColor(C.critical)
            .text(`[Page render error — ${page.name}]`, MARGIN, MARGIN + 50);
        }
        addFooter(doc, pageNum, TOTAL_PAGES);
      });

      doc.end();

      console.log(
        `[MGD][PDF] Pages rendered: ${pages.length}, ` +
        `findings=${report?.findings?.length ?? 0}, ` +
        `rootCauses=${report?.rootCauses?.length ?? 0}, ` +
        `recommendations=${report?.recommendations?.length ?? 0}, ` +
        `benchmarks=${report?.benchmarks?.length ?? 0}`,
      );
    } catch (err) {
      console.error("[MGD][PDF] Fatal error:", err);
      reject(err);
    }
  });
}
