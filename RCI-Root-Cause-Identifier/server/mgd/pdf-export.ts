// Generates boardroom-ready PDF reports from MGDReport objects using PDFKit.
// Seven pages: Cover → Summary → Benchmarks → Findings → Root Causes →
//              Recommendations → Narrative.
//
// Design principles:
//   • Never throws — every page renderer wrapped in try/catch with graceful fallback.
//   • All text passed through safeText() to prevent null/undefined rendering.
//   • severityColor() and priorityColor() provide consistent visual language.
//   • Page numbers and footer on every page via addFooter().
//   • [MGD][PDF] prefix on all log lines.
// ─────────────────────────────────────────────────────────────────────────────

