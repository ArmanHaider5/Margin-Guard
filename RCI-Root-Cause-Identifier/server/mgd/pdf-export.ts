// ── Helpers ───────────────────────────────────────────────────────────────────

/** Coerce any value to a safe non-empty string. */
export function safeText(v: unknown, fallback = "—"): string {
  if (v == null) return fallback;
  const s = String(v).trim();
  return s.length > 0 ? s : fallback;
}

/** Truncate text to a max length with ellipsis. */
function trunc(text: string, max: number): string {
  const s = safeText(text);
  return s.length > max ? s.slice(0, max - 1) + "…" : s;
}

/** Severity → color hex. */
export function severityColor(severity: string): string {
  const s = (severity ?? "").toUpperCase();
  if (s === "CRITICAL") return C.critical;
  if (s === "HIGH")     return C.high;
  if (s === "MEDIUM")   return C.medium;
  return C.low;
}

/** Priority → color hex (same mapping as severity). */
export function priorityColor(priority: string): string {
  return severityColor(priority);
}

/** Benchmark status → color hex. */
function benchmarkColor(status: string): string {
  const s = (status ?? "").toUpperCase();
  if (s === "CRITICAL") return C.critical;
  if (s === "ELEVATED") return C.elevated;
  if (s === "WATCHLIST")return C.watchlist;
  return C.healthy;
}

// ── Layout helpers ─────────────────────────────────────────────────────────────

/** Draw a thin horizontal rule. */
function rule(doc: PDFKit.PDFDocument, y: number, color = C.rule): void {
  doc.save()
    .strokeColor(color).lineWidth(0.5)
    .moveTo(MARGIN, y).lineTo(MARGIN + CONTENT_W, y).stroke()
    .restore();
}

/** Fill a rectangle. */
function fillRect(doc: PDFKit.PDFDocument, x: number, y: number, w: number, h: number, color: string): void {
  doc.save().rect(x, y, w, h).fill(color).restore();
}

/** Render the standard footer with page number on the current page. */
function addFooter(doc: PDFKit.PDFDocument, pageNum: number, totalPages: number): void {
  doc.save();
  rule(doc, FOOTER_Y - 4, C.rule);
  doc.font(F.regular).fontSize(7).fillColor(C.light)
    .text("Generated by MGD Operational Intelligence · Scope Optix Sdn. Bhd. · Confidential",
      MARGIN, FOOTER_Y, { width: CONTENT_W - 60, align: "left" });
  doc.font(F.regular).fontSize(7).fillColor(C.light)
    .text(`Page ${pageNum} of ${totalPages}`,
      MARGIN, FOOTER_Y, { width: CONTENT_W, align: "right" });
  doc.restore();
}

/** Draw a small filled severity pill badge. Returns its rendered width. */
function severityBadge(doc: PDFKit.PDFDocument, x: number, y: number, label: string, color: string): number {
  const txt = safeText(label);
  const tw = doc.font(F.bold).fontSize(7).widthOfString(txt);
  const pw = tw + 10;
  const ph = 12;
  doc.save()
    .roundedRect(x, y - 1, pw, ph, 3).fill(color);
  doc.fillColor("#ffffff").font(F.bold).fontSize(7)
    .text(txt, x + 5, y + 1, { lineBreak: false });
  doc.restore();
  return pw + 6;
}

/** Render a mini progress/confidence bar. */
function confBar(doc: PDFKit.PDFDocument, x: number, y: number, w: number, pct: number, color: string): void {
  doc.save()
    .roundedRect(x, y, w, 5, 2).fillColor(C.rule).fill()
    .roundedRect(x, y, Math.max(4, w * (pct / 100)), 5, 2).fillColor(color).fill()
    .restore();
}

/** Print a labelled key–value row. Returns new y offset. */
function kvRow(doc: PDFKit.PDFDocument, x: number, y: number, label: string, value: string, w = CONTENT_W): number {
  doc.font(F.bold).fontSize(8).fillColor(C.muted)
    .text(safeText(label).toUpperCase(), x, y, { width: 130 });
  doc.font(F.regular).fontSize(8).fillColor(C.body)
    .text(safeText(value), x + 135, y, { width: w - 135 });
  return y + 13;
}

